def test_pi_commit_failure_keeps_failed_preunlock_record_held_without_final_result(runtime, tmp_path):
    import sqlite3
    from mcu_process_handoff import McuProcessEventHandoff
    execution, start, failed, now = failed_initial(runtime, tmp_path, "UNAVAILABLE")
    lib, endpoint, _, replies, *_ = runtime
    identity = {key: value for key, value in original_scope(start, clean=True).items() if key != "queryId"} | {
        "eventMessageType": NAME, "stepSequence": 0, "configVersion": start["configVersion"]}
    store = EdgeStore(str(tmp_path / "commit-failure.db"))
    store.initialize()
    sent = []

    def write(frame):
        sent.append(uart.decode_frame(frame, sender_role="EDGE")["messageName"])
        assert lib.McuControlEndpoint_Feed(endpoint, frame, len(frame), now) == 1
        return len(frame)

    try:
        replies.clear()
        client = McuProcessEventHandoff(store, write, identity)
        client.poll(now)
        assert client.accept_frame(replies.pop(0), now)
        event = replies.pop(0)
        store._conn.set_authorizer(lambda action, first, *_:
            sqlite3.SQLITE_DENY if action == sqlite3.SQLITE_TRANSACTION and first == "COMMIT" else sqlite3.SQLITE_OK)
        with pytest.raises(sqlite3.DatabaseError):
            client.accept_frame(event, now)
        store._conn.set_authorizer(None)
        assert sent == ["QUERY_PROCESS_EVENT"]
        assert store.get_native_process_event(NAME, 42, failed["mcuEventSequence"]) is None
        now = advance(runtime, now, 1000)
        assert exchange(runtime, "QUERY_PROCESS_EVENT", identity | {"queryId": 1}, now=now)[0][1]["status"] == "HELD"
        assert exchange(runtime, "QUERY_WORK", original_scope(start, clean=True), now=now)[0][1]["status"] == "RUNNING"
        assert store.list_native_result_report_tasks() == [] and not facts(runtime, now)["cleanLockPowered"] and execution
    finally:
        store._conn.set_authorizer(None)
        store.close()
