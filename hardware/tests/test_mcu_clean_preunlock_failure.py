def test_failed_preunlock_finishes_only_after_exact_custody_without_any_unlock_or_human_confirmation(runtime, tmp_path):
    execution = enable(runtime)
    lib, endpoint, preparation, *_ = runtime
    start, failed, now = prepared(runtime, tmp_path, clean=True, mode="unavailable", saved=False)
    assert failed["measurementKind"] == "UNAVAILABLE" and failed["measurementElapsedMs"] == 5000
    now = advance(runtime, now, 60000)
    state = exchange(runtime, "QUERY_WORK", original_scope(start, clean=True), now=now)[0][1]
    assert state["status"] == "RUNNING" and state["phase"] == "CLEAN_FINALIZING"
    store = EdgeStore(str(tmp_path / "failed-before-unlock.db"))
    store.initialize()
    try:
        assert store.acquire_work_slot("CLEAN", start["operationUid"], 1, {"phase": "NATIVE_CLEAN"})
        occupancy = store.get_work_slot()
        save_intent(runtime, start, NAME, 0, now, store)
        writes = lib.TestFacts_Writes()
        assert lib.McuWorkPreparation_Poll(preparation, endpoint, now)
        result = held_result(runtime, start, now)
        assert result["finishReason"] == "FAILED" and result["cleanActionSequence"] == 0
        assert result["initialKind"] == "UNAVAILABLE" and result["initialFaultCode"] == "WEIGHT_TIMEOUT"
        assert result["initialMeasurementUid"] == failed["measurementUid"]
        assert result["initialMcuEventSequence"] == failed["mcuEventSequence"]
        assert result["initialSourceMcuBootId"] == 42 and result["completedUptimeMs"] == failed["uptimeMs"] == 5000
        assert result["finalKind"] == "NOT_TAKEN" and result["finalMeasurementUid"] == "00000000-0000-0000-0000-000000000000"
        assert result["finalWeightGrams"] == 0 and result["finalSampleCount"] == 0
        assert not result["physicalCloseConfirmed"] and not result["negativeWeightAnomaly"] and result["deliveryRoundCount"] == 0
        assert result["originCommandUid"] == start["mcuCommandUid"] and result["originCommandSequence"] == start["commandSequence"]
        assert result["configVersion"] == start["configVersion"]
        assert facts(runtime, now)["measurementSequence"] == 1 and not facts(runtime, now)["cleanLockPowered"]
        assert not facts(runtime, now)["pb6Output"] and not facts(runtime, now)["pb7Output"]
        assert events(runtime, now)[0][1]["status"] == "NOT_FOUND" and lib.TestFacts_Writes() == writes
        assert store.list_native_result_report_tasks() == []
        receipt = store.save_native_mcu_result(uart.encode_payload("WORK_RESULT", result))
        assert exchange(runtime, "RESULT_SAVED", payload=receipt["savedPayload"], now=now)[0][1]["status"] == "RELEASED"
        assert store.get_work_slot() == occupancy
        assert [row["state"] for row in store.list_native_result_report_tasks()] == ["PENDING_CLASSIFICATION"]
        now = advance(runtime, now, 60000)
        # Timer ticks may refresh the existing 00 output; no mechanical command
        # or energized output is generated by foreground result finalization.
        assert facts(runtime, now)["measurementSequence"] == 1 and not facts(runtime, now)["cleanLockPowered"]
        assert not facts(runtime, now)["pb6Output"] and not facts(runtime, now)["pb7Output"] and execution
    finally:
        store.close()


def test_interrupted_initial_clean_measurement_retains_partial_attempt_as_failed_without_unlock(runtime, tmp_path):
    execution = enable(runtime)
    configured(runtime, applied=True)
    start = start_values("START_CLEAN_OPERATION")
    assert exchange(runtime, "START_CLEAN_OPERATION", start)[0][1]["outcome"] == "ACCEPTED"
    now = take_samples(runtime, [300])
    lib, endpoint, preparation, *_ = runtime
    # Explicit acquisition interruption, not a claim of automatic clean update
    # or expiry detection. This is already a real terminal measurement kind.
    assert lib.McuWeightRun_Interrupt(lib.TestPreparation_Weight(preparation), 1, now)
    now = advance(runtime, now, 0)
    store = EdgeStore(str(tmp_path / "interrupted-preunlock.db"))
    store.initialize()
    try:
        failed = save_intent(runtime, start, NAME, 0, now, store)
        assert failed["measurementKind"] == "INTERRUPTED" and failed["sampleCount"] == 1
        assert lib.McuWorkPreparation_Poll(preparation, endpoint, now)
        result = held_result(runtime, start, now)
        assert result["finishReason"] == "FAILED" and result["cleanActionSequence"] == 0
        assert result["initialKind"] == "INTERRUPTED" and result["initialFaultCode"] == "MEASUREMENT_INTERRUPTED"
        assert result["initialElapsedMs"] == 20 and result["initialSampleCount"] == 1
        assert result["initialMeasurementUid"] == failed["measurementUid"] and result["completedUptimeMs"] == failed["uptimeMs"]
        assert result["finalKind"] == "NOT_TAKEN" and not result["physicalCloseConfirmed"]
        assert events(runtime, now)[0][1]["status"] == "NOT_FOUND" and execution
    finally:
        store.close()


