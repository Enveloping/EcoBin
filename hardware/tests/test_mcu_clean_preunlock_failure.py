@pytest.mark.parametrize("case", ["no_receipt", "wrong_digest", "wrong_type", "empty_slot", "future_poll", "old_poll"])
def test_missing_or_inexact_custody_and_invalid_poll_time_cannot_freeze_failure(runtime, tmp_path, case):
    execution = enable(runtime)
    saved = case in {"empty_slot", "future_poll", "old_poll"}
    start, failed, now = prepared(runtime, tmp_path, clean=True, mode="unavailable", saved=saved)
    lib, endpoint, preparation, *_ = runtime
    poll_at = now
    if case in {"wrong_digest", "wrong_type"}:
        receipt = dict(mcuBootId=42, mcuEventSequence=failed["mcuEventSequence"], eventMessageType=NAME,
            eventDigestSha256=uart.compute_process_event_digest(NAME, uart.encode_payload(NAME, failed)))
        receipt.update({"eventDigestSha256": "00" * 32} if case == "wrong_digest" else {"eventMessageType": "WORK_PREOPEN_WEIGHT_READY"})
        assert exchange(runtime, "PROCESS_EVENT_SAVED", receipt, now=now)[0][1]["status"] == "IDENTITY_CONFLICT"
    elif case == "empty_slot":
        lib.McuProcessEventSlot_Init(lib.TestPreparation_Process(endpoint), 42)
    elif case == "future_poll":
        poll_at += 1
    elif case == "old_poll":
        poll_at -= 1
    writes = lib.TestFacts_Writes()
    assert lib.McuWorkPreparation_Poll(preparation, endpoint, poll_at)
    assert exchange(runtime, "QUERY_WORK", original_scope(start, clean=True), now=now)[0][1]["status"] == "RUNNING"
    assert lib.TestFacts_Writes() == writes and not facts(runtime, now)["cleanLockPowered"] and execution
    if case in {"future_poll", "old_poll"}:
        assert lib.McuWorkPreparation_Poll(preparation, endpoint, now)
        assert held_result(runtime, start, now)["completedUptimeMs"] == failed["uptimeMs"]


