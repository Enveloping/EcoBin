def test_failed_new_clean_does_not_inherit_previous_successful_clean_confirmation_or_final_weight(runtime, tmp_path):
    from hardware.tests.test_mcu_clean_confirmation import measured_candidate, confirm
    from hardware.tests.test_mcu_clean_confirmation import NAME as CONFIRMATION
    execution, previous, _, final, now, store = measured_candidate(runtime, tmp_path)
    try:
        assert confirm(runtime, execution, previous, final, now)
        save_intent(runtime, previous, CONFIRMATION, 1, now, store)
        now = advance(runtime, now, 0)
        old_result = held_result(runtime, previous, now)
        old_raw = uart.encode_payload("WORK_RESULT", old_result)
        receipt = store.save_native_mcu_result(old_raw)
        assert exchange(runtime, "RESULT_SAVED", payload=receipt["savedPayload"], now=now)[0][1]["status"] == "RELEASED"
        # New, separately authorized work at the C boundary, after result-slot
        # release. This does not simulate or claim Pi/cloud business admission.
        start = start_values("START_CLEAN_OPERATION", commandSequence=8,
            mcuCommandUid="88888888-8888-4888-8888-888888888888", operationUid="99999999-9999-4999-8999-999999999999")
        assert exchange(runtime, "START_CLEAN_OPERATION", start, now=now)[0][1]["outcome"] == "ACCEPTED"
        now = advance(runtime, now, 5000)
        failed = save_intent(runtime, start, NAME, 0, now, store)
        now = advance(runtime, now, 0)
        result = held_result(runtime, start, now)
        assert result["resultSequence"] == 2 and result["cleanActionSequence"] == 0
        assert result["originCommandUid"] == start["mcuCommandUid"] != previous["mcuCommandUid"]
        assert not result["physicalCloseConfirmed"] and result["finalKind"] == "NOT_TAKEN"
        assert result["initialMeasurementUid"] == failed["measurementUid"] != old_result["finalMeasurementUid"]
        assert result["initialKind"] == "UNAVAILABLE" and result["finishReason"] == "FAILED"
        assert store.get_native_mcu_result(42, 1)["payload"] == old_raw
        assert facts(runtime, now)["measurementSequence"] == 3 and not facts(runtime, now)["cleanLockPowered"]
        assert events(runtime, now)[0][1]["status"] == "NOT_FOUND"
    finally:
        store.close()


